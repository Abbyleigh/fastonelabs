"""Generate the browser contract from Pydantic; --check detects drift."""
import json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'backend'))
from race_state import UnifiedRaceState
schema=UnifiedRaceState.model_json_schema(mode="serialization")
def typ(s):
 if '$ref'in s:return s['$ref'].split('/')[-1]
 if 'const'in s:return json.dumps(s['const'])
 if 'enum'in s:return ' | '.join(json.dumps(v)for v in s['enum'])
 if 'anyOf'in s:return ' | '.join(typ(v)for v in s['anyOf'])
 t=s.get('type')
 if t=='array':return f"ReadonlyArray<{typ(s.get('items',{}))}>"
 return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(t,'unknown')
def declaration(name,s):
 required=s.get('required',[])
 return 'export type '+name+' = {\n'+''.join(f"  readonly {k}{''if k in required else '?'}: {typ(v)};\n"for k,v in s['properties'].items())+'};\n'
source='// Generated by tools/generate_race_contract.py. Do not edit by hand.\n'+''.join(declaration(k,v)for k,v in schema.get('$defs',{}).items())+declaration('UnifiedRaceState',schema)
outputs={ROOT/'frontend/src/race/unifiedRaceState.ts':source,ROOT/'frontend/src/race/unifiedRaceState.schema.json':json.dumps(schema,indent=2)+'\n'}
for path,text in outputs.items():
 if '--check'in sys.argv:
  if not path.exists()or path.read_text()!=text:raise SystemExit(f'Contract out of date: {path}')
 else:path.write_text(text)
print('Race contract verified'if'--check'in sys.argv else'Race contract generated')
