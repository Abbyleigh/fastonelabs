"""Generate TypeScript contracts from FastAPI/Pydantic; --check detects drift."""
import argparse
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'backend'))
from heritage.router import SearchResponse, DetailResponse


def ts(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'const' in schema:
        import json
        return json.dumps(schema['const'])
    if 'enum' in schema:
        import json
        return ' | '.join(json.dumps(v) for v in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(dict.fromkeys(ts(s) for s in schema['anyOf']))
    kind = schema.get('type')
    if kind == 'array':
        return f'Array<{ts(schema["items"])}>'
    if kind == 'object':
        if 'properties' not in schema:
            return 'Record<string, ' + ts(schema.get('additionalProperties', {})) + '>'
        required = schema.get('required', [])
        return '{\n' + '\n'.join('  ' + k + ('' if k in required else '?') + ': ' + ts(v) + ';' for k, v in schema['properties'].items()) + '\n}'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


def generated():
    definitions = {}
    for model in (SearchResponse, DetailResponse):
        schema = model.model_json_schema(mode='serialization')
        definitions.update(schema.pop('$defs', {}))
        definitions[model.__name__] = schema
    return '// Generated by tools/generate_heritage_contracts.py. Do not edit.\n' + '\n\n'.join('export type ' + k + ' = ' + ts(v) + ';' for k, v in sorted(definitions.items())) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / 'frontend/src/heritage/contracts.ts'
    content = generated()
    if args.check:
        if target.read_text() != content:
            raise SystemExit('Heritage contracts differ; regenerate them')
        print('Heritage contracts match Pydantic schemas')
    else:
        target.write_text(content)
