"""Lossless distribution for GLBs above static-host per-file limits.
Input files are explicit local originals. Never downloads, edits geometry or removes originals.
"""
from pathlib import Path
import gzip,hashlib,json,sys
ROOT=Path(__file__).resolve().parents[1]
PUBLIC=ROOT/'frontend/public'
CHUNK=20_000_000

def pack(logical,raw):
 compressed=gzip.compress(raw,compresslevel=9,mtime=0);stem=Path(logical).stem;folder=PUBLIC/'models/cars/packed';folder.mkdir(parents=True,exist_ok=True);chunks=[]
 for index,start in enumerate(range(0,len(compressed),CHUNK)):
  data=compressed[start:start+CHUNK];path=folder/f'{stem}.glb.gz.part{index}.bin';path.write_bytes(data);chunks.append({'path':'/'+str(path.relative_to(PUBLIC)),'bytes':len(data)})
 return {'encoding':'gzip','bytes':len(raw),'sha256':hashlib.sha256(raw).hexdigest(),'compressedSha256':hashlib.sha256(compressed).hexdigest(),'chunks':chunks}
if __name__=='__main__':
 if len(sys.argv)<3 or len(sys.argv[1:])%2:raise SystemExit('Usage: python tools/pack_large_models.py /models/logical.glb /local/original.glb [...]')
 manifest_path=PUBLIC/'models/packed-models.json';manifest=json.loads(manifest_path.read_text())if manifest_path.exists()else {'version':1,'models':{}}
 for logical,source in zip(sys.argv[1::2],sys.argv[2::2]):
  if not logical.startswith('/models/')or not logical.endswith('.glb'):raise ValueError('Expected a logical GLB path')
  manifest['models'][logical]=pack(logical,Path(source).read_bytes())
 manifest_path.write_text(json.dumps(manifest,indent=2)+'\n')
 (ROOT/'frontend/src/packedModels.ts').write_text('// Generated by tools/pack_large_models.py. Compressed parts preserve original GLB bytes.\nexport const packedModels:Record<string,{encoding:string;bytes:number;sha256:string;compressedSha256:string;chunks:{path:string;bytes:number}[]}>= '+json.dumps(manifest['models'],indent=2)+';\n')
 print('Packed models:',len(manifest['models']))
